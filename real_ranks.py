def get_real_rank(province, category, score):
    """
    从真实一分一段表中插值获取位次
    返回: (rank, is_real) — is_real=True表示真实数据, False表示外推
    """
    table = REAL_RANK_TABLES.get(province, {}).get(category)
    if not table:
        return None, False
    
    # 二分查找最近的两个数据点做线性插值
    if score >= table[0][0]:
        return table[0][1], True  # 超过最高分
    if score < table[-1][0]:
        # 低于最低分: 外推
        last_s, last_r = table[-1]
        second_s, second_r = table[-2]
        slope = (second_r - last_r) / (second_s - last_s)
        rank = int(last_r + (score - last_s) * slope)
        return max(1, rank), False
    
    for i in range(len(table) - 1):
        s1, r1 = table[i]
        s2, r2 = table[i + 1]
        if s2 <= score <= s1:
            # 线性插值
            if s1 == s2:
                return r1, True
            ratio = (score - s2) / (s1 - s2)
            rank = int(r2 + (r1 - r2) * ratio)
            return rank, True
    
    return table[-1][1], False


# 用于seed的rank生成函数
def estimate_rank_for_seed(province, category, score):
    """为种子数据生成位次：优先用真实数据，否则用改进的非线性公式"""
    rank, is_real = get_real_rank(province, category, score)
    if is_real:
        return rank
    
    # 对无真实数据的省份，用改进公式
    # 非线性: rank ∝ (750-score)^1.5 更贴合实际分布
    if province in ("河南","广东","四川","山东"):
        coef = 2000
    elif province in ("北京","上海","天津"):
        coef = 200
    elif province in ("江苏","湖北","湖南","浙江"):
        coef = 800
    else:
        coef = 1200
    
    rank = max(1, int(((750 - score) / 100) ** 1.6 * coef))
    return rank
