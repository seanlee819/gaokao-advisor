# 执行更新
# ============================================================
def expand():
    conn = get_db()
    cur = conn.cursor()
    
    # 1. 清空旧专业和关联
    cur.execute("DELETE FROM uni_majors")
    cur.execute("DELETE FROM majors")
    
    # 2. 插入新专业
    for name, cat, emp, salary, diff, desc in EXPANDED_MAJORS:
        cur.execute(
            "INSERT INTO majors (name,category,employment_score,avg_salary,difficulty_offset,description) VALUES (?,?,?,?,?,?)",
            (name, cat, emp, salary, diff, desc))
    conn.commit()
    print(f"1. 插入 {len(EXPANDED_MAJORS)} 个专业, {len(set(m[1] for m in EXPANDED_MAJORS))} 个门类")
    
    # 3. 获取所有大学及其类型
    unis = cur.execute("SELECT id, name, level, type, city FROM universities").fetchall()
    print(f"2. {len(unis)} 所院校, 开始生成专业关联...")
    
    # 4. 按门类分组专业
    majors_by_cat = defaultdict(list)
    for name, cat, emp, salary, diff, desc in EXPANDED_MAJORS:
        majors_by_cat[cat].append((name, emp, diff))
    
    # 5. 为每所院校分配优势专业
    rng = random.Random(42)
    link_count = 0
    uni_with_links = 0
    
    for uid, name, level, utype, city in unis:
        weights = TYPE_MAJOR_WEIGHTS.get(utype, TYPE_MAJOR_WEIGHTS.get("综合", {}))
        
        # 按权重抽取专业门类, 然后从每个门类中选前几个热门专业
        assigned = set()
        for cat, weight in weights.items():
            if weight <= 0 or cat not in majors_by_cat:
                continue
            # 该门类下选 weight 个最热门的专业 (按employment_score排序)
            cat_majors = sorted(majors_by_cat[cat], key=lambda x: x[1], reverse=True)
            selected = rng.sample(cat_majors, min(weight + 1, len(cat_majors)))
            for mname, _, _ in selected:
                assigned.add(mname)
        
        # 985/211 额外给更多专业
        if level in ("C9","985","211","双一流") or any(t in str(level) for t in ["985","211"]):
            extras = rng.sample([m[0] for m in EXPANDED_MAJORS if m[0] not in assigned], 
                               min(5, len(EXPANDED_MAJORS) - len(assigned)))
            assigned.update(extras)
        
        for mname in assigned:
            cur.execute(
                "INSERT INTO uni_majors (university_id, major_id, is_advantage) SELECT ?, id, 1 FROM majors WHERE name=?",
                (uid, mname))
            link_count += 1
        
        uni_with_links += 1
    
    conn.commit()
    conn.close()
    print(f"3. {link_count} 条优势专业关联, {uni_with_links} 所院校")
    
    # Stats
    conn = get_db()
    c = conn.cursor()
    mcount = c.execute("SELECT COUNT(*) FROM majors").fetchone()[0]
    lcount = c.execute("SELECT COUNT(*) FROM uni_majors").fetchone()[0]
    cats = c.execute("SELECT DISTINCT category FROM majors ORDER BY category").fetchall()
    conn.close()
    
    print(f"\n=== 完成 ===")
    print(f"  专业: {mcount}")
    print(f"  关联: {lcount}")
    print(f"  门类: {len(cats)} ({', '.join(c[0] for c in cats)})")


if __name__ == "__main__":
    expand()
