def generate_realistic_names():
    """生成真实风格的院校名称"""
    rng = random.Random(42)
    all_universities = {}
    used_names = set()
    
    # 1. Add all elite schools with real names
    for name, info in REAL_ELITE.items():
        if info is None:
            continue
        city, level, utype, tier = info
        code = f"41{rng.randint(100000, 999999):06d}"
        all_universities[name] = (code, city, level, utype, tier)
        used_names.add(name)
    
    # 2. Add prov_key schools with real names
    for name, city, utype in PROV_KEY_NAMES:
        if name in used_names:
            continue
        code = f"41{rng.randint(100000, 999999):06d}"
        all_universities[name] = (code, city, "省重点", utype, "prov_key")
        used_names.add(name)
    
    # 3. Generate remaining prov_key from templates
    for prov, cities in CITIES_BY_PROVINCE.items():
        for template, utype in PROV_KEY_TEMPLATES:
            for city in cities[:3]:
                name = template.format(city=city, province=PROV_SHORT[prov])
                if name not in used_names:
                    all_universities[name] = (f"41{rng.randint(100000,999999):06d}", city, "省重点", utype, "prov_key")
                    used_names.add(name)
                    break
    
    # 4. Generate public UG
    for prov, cities in CITIES_BY_PROVINCE.items():
        count = 0
        target = {"北京":50,"天津":25,"上海":35,"重庆":25,"江苏":70,"广东":60,"山东":65,
                  "河南":55,"湖北":60,"湖南":50,"四川":50,"河北":55,"陕西":50}.get(prov, 35)
        for template, utype in PUBLIC_UG_SUFFIXES:
            for city in cities[:4]:
                if count >= target:
                    break
                name = template.format(city=city, province=PROV_SHORT[prov])
                if name not in used_names and len(name) <= 12:
                    all_universities[name] = (f"41{rng.randint(100000,999999):06d}", city, "公办本科", utype, "pub_ug")
                    used_names.add(name)
                    count += 1
    
    # 5. Generate private UG
    for prov, cities in CITIES_BY_PROVINCE.items():
        count = 0
        target = {"广东":25,"江苏":22,"湖北":18,"山东":20,"河南":20,"河北":18}.get(prov, 10)
        for template, utype in PRIVATE_UG_SUFFIXES:
            for city in cities[:3]:
                if count >= target:
                    break
                name = template.format(city=city, province=PROV_SHORT[prov])
                if name not in used_names and len(name) <= 12:
                    all_universities[name] = (f"41{rng.randint(100000,999999):06d}", city, "民办本科", utype, "priv_ug")
                    used_names.add(name)
                    count += 1
    
    # 6. Generate public vocational
    for prov, cities in CITIES_BY_PROVINCE.items():
        count = 0
        target = {"河南":65,"广东":55,"山东":60,"江苏":60,"四川":55,"河北":45}.get(prov, 30)
        for template, utype in PUBLIC_VOC_SUFFIXES:
            for city in cities[:3]:
                if count >= target:
                    break
                name = template.format(city=city, province=PROV_SHORT[prov])
                if name not in used_names and len(name) <= 15:
                    all_universities[name] = (f"41{rng.randint(100000,999999):06d}", city, "公办专科", utype, "pub_voc")
                    used_names.add(name)
                    count += 1
    
    # 7. Generate private vocational
    for prov, cities in CITIES_BY_PROVINCE.items():
        count = 0
        target = {"河南":15,"广东":12,"四川":15,"山东":10}.get(prov, 6)
        for template, utype in PRIVATE_VOC_SUFFIXES:
            for city in cities[:2]:
                if count >= target:
                    break
                name = template.format(city=city, province=PROV_SHORT[prov])
                if name not in used_names and len(name) <= 15:
                    all_universities[name] = (f"41{rng.randint(100000,999999):06d}", city, "民办专科", utype, "priv_voc")
                    used_names.add(name)
                    count += 1
    
    # Convert to list
    result = []
    for name, (code, city, level, utype, tier) in all_universities.items():
        result.append([name, code, city, level, utype, tier])
    
    return result

