TIER_MAJOR_COUNT = {
    "C9": 5, "top985": 5, "mid985": 4, "other985": 4,
    "top211": 4, "mid211": 4, "other211": 3,
    "prov_key": 3, "pub_ug": 3, "priv_ug": 3,
    "pub_voc": 2, "priv_voc": 2,
}

def generate_all_major_links(schools):
    """为所有3075所院校生成专业关联"""
    import random
    rng = random.Random(42)
    links = {}
    
    for name, code, city, level, utype, tier in schools:
        # 精英院校用手工数据
        if name in ELITE_MAJOR_MAP:
            links[name] = ELITE_MAJOR_MAP[name]
            continue
        
        # 其他院校按类型自动分配
        candidates = TYPE_MAJOR_MAP.get(utype, TYPE_MAJOR_MAP["综合"])
        count = TIER_MAJOR_COUNT.get(tier, 2)
        # 从候选专业中随机选count个
        selected = rng.sample(candidates, min(count, len(candidates)))
        links[name] = selected
    
    return links

