def seed_province_lines():
    conn = get_db()
    cur = conn.cursor()
    for item in PROVINCE_LINES:
        try:
            cur.execute(
                """INSERT OR REPLACE INTO province_lines
                   (province, year, category, batch, score, rank)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                item
            )
        except Exception as e:
            print(f"  Skip {item}: {e}")
    conn.commit()
    conn.close()
    print(f"  Inserted {len(PROVINCE_LINES)} province line records")


def seed_universities():
    conn = get_db()
    cur = conn.cursor()
    for item in UNIVERSITIES:
        cur.execute(
            """INSERT OR REPLACE INTO universities
               (name, code, city, level, type) VALUES (?, ?, ?, ?, ?)""",
            item
        )
    conn.commit()
    conn.close()
    print(f"  Inserted {len(UNIVERSITIES)} universities")


