def seed_uni_majors():
    """插入院校-优势专业关联"""
    conn = get_db()
    # 获取名称->ID映射
    universities = {r["name"]: r["id"] for r in conn.execute("SELECT id, name FROM universities").fetchall()}
    majors = {r["name"]: r["id"] for r in conn.execute("SELECT id, name FROM majors").fetchall()}

    cur = conn.cursor()
    count = 0
    for uni_name, major_names in UNI_MAJOR_LINKS.items():
        uni_id = universities.get(uni_name)
        if not uni_id:
            continue
        for mn in major_names:
            mid = majors.get(mn)
            if mid:
                cur.execute(
                    """INSERT OR REPLACE INTO uni_majors (university_id, major_id, is_advantage)
                       VALUES (?, ?, 1)""",
                    (uni_id, mid)
                )
                count += 1
    conn.commit()
    conn.close()
    print(f"  Inserted {count} university-major links")


