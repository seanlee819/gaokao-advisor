def generate_admission_scores():
    """根据省份批次线和院校偏移量生成录取分数"""
    conn = get_db()

    # 获取所有省份批次线
    lines = conn.execute("SELECT * FROM province_lines ORDER BY province, year, category, batch").fetchall()

    # 获取所有大学
    unis = conn.execute("SELECT * FROM universities").fetchall()
    uni_map = {u["name"]: u["id"] for u in unis}

    records = []

    for line in lines:
        province = line["province"]
        year = line["year"]
        category = line["category"]
        batch = line["batch"]
        batch_score = line["score"]

        # 只为本科批次生成录取数据（所有含"本科"或"一段线"的批次）
        if "专科" in batch or batch == "二段线":
            continue

        for uni_name, uni_id in uni_map.items():
            if uni_name not in UNI_OFFSETS:
                continue

            sci_offset, arts_offset = UNI_OFFSETS[uni_name]

            # 确定用哪个偏移
            if category in ("理科", "物理类", "综合"):
                offset = sci_offset
            elif category in ("文科", "历史类"):
                offset = arts_offset
            else:
                offset = (sci_offset + arts_offset) // 2

            # 山东/北京是综合类，用理科偏移
            if province in ("山东", "北京") and category == "综合":
                offset = sci_offset

            # 非一本省份的本科批，偏移适当调整
            if batch in ("本科批", "一段线") and province not in ("北京",):
                offset = offset

            # 年份微调（每年有波动）
            import random
            rng = random.Random(f"{uni_name}{province}{year}")
            year_jitter = rng.randint(-5, 8)
            min_score = batch_score + offset + year_jitter
            avg_score = min_score + rng.randint(3, 12)
            max_score = avg_score + rng.randint(5, 20)

            # 位次估计（粗略）
            # 位次 = (750-分数) * 系数。各省考生规模不同，系数校准到与实际省控线位次匹配
            rank_factor = {
                "河南": 500, "广东": 390, "四川": 310, "山东": 390,
                "江苏": 210, "湖北": 230, "湖南": 260, "北京": 60,
            }.get(province, 300)
            min_rank = max(1, int((750 - min_score) * rank_factor))

            records.append((uni_id, province, year, category, batch,
                          min_score, avg_score, max_score, min_rank))

    cur = conn.cursor()
    for r in records:
        try:
            cur.execute(
                """INSERT OR REPLACE INTO admission_scores
                   (university_id, province, year, category, batch,
                    min_score, avg_score, max_score, min_rank)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                r
            )
        except Exception as e:
            pass

    conn.commit()
    conn.close()
    print(f"  Inserted {len(records)} admission score records")


