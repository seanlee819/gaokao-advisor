# 执行: 注入数据库
# ============================================================
def apply_all():
    conn = get_db()
    cur = conn.cursor()
    
    # --- A: 注入真实院校录取分 ---
    print("A: 注入真实录取分...")
    updated_a = 0; not_found_a = 0
    for name, (score, rank) in REAL_2024_HENAN_SCI.items():
        uni = conn.execute("SELECT id FROM universities WHERE name=?", (name,)).fetchone()
        if not uni:
            not_found_a += 1
            continue
        uid = uni['id']
        # 更新河南理科所有年份
        for year, adj in [(2024,0),(2025,0),(2023,2)]:
            cur.execute("""
                UPDATE admission_scores SET min_score=?, avg_score=?, max_score=?, min_rank=?
                WHERE university_id=? AND province='河南' AND category='理科' AND year=?
            """, (score+adj, score+adj+5, score+adj+15, max(1,rank-adj*200), uid, year))
            updated_a += cur.rowcount
    conn.commit()
    print(f"  更新: {updated_a}条, 未找到: {not_found_a}所")
    
    # --- C: 注入真实专业分 → 更新 difficulty_offset ---
    print("\nC: 注入真实专业分 (更新difficulty_offset)...")
    updated_c = 0
    for school_name, majors in REAL_MAJOR_SCORES.items():
        uni = conn.execute("SELECT id, name FROM universities WHERE name=?", (school_name,)).fetchone()
        if not uni: continue
        
        # 获取该校平均录取分
        avg = conn.execute("""
            SELECT AVG(min_score) FROM admission_scores 
            WHERE university_id=? AND province='河南' AND category='理科' AND year=2024
        """, (uni['id'],)).fetchone()[0]
        if not avg: continue
        
        for major_name, (major_score, major_rank) in majors.items():
            mid = conn.execute("SELECT id FROM majors WHERE name=?", (major_name,)).fetchone()
            if not mid: continue
            
            # 计算该专业的真实偏移量
            real_offset = major_score - int(avg)
            
            # 更新majors表的difficulty_offset (用加权平均)
            cur.execute("""
                UPDATE majors SET difficulty_offset = ?
                WHERE id = ?
            """, (round(real_offset), mid['id']))
            
            # 确保该专业在此校的uni_majors中有记录
            cur.execute("""
                INSERT OR IGNORE INTO uni_majors (university_id, major_id, is_advantage)
                VALUES (?, ?, 1)
            """, (uni['id'], mid['id']))
            
            updated_c += 1
    conn.commit()
    print(f"  更新专业偏移: {updated_c}条")
    
    # --- B: 层次感知的专业难度偏移 ---
    print("\nB: 层次感知专业偏移...")
    # 获取所有专业当前偏移
    all_majors = conn.execute("SELECT id, name, category, difficulty_offset FROM majors").fetchall()
    
    # 按专业类别设定基准偏移，再根据层次微调
    BASE_OFFSETS = {
        "计算机科学与技术": 10, "人工智能": 12, "软件工程": 8,
        "数据科学与大数据技术": 10, "电子信息工程": 6, "通信工程": 5,
        "电气工程及其自动化": 5, "自动化": 4, "机械工程": 0,
        "土木工程": -3, "建筑学": 3, "材料科学与工程": -2,
        "车辆工程": 2, "航空航天工程": 3, "生物医学工程": 1,
        "数学与应用数学": 2, "物理学": -2, "化学": -3, "统计学": 6,
        "临床医学": 8, "口腔医学": 12, "药学": 1,
        "金融学": 6, "经济学": 4, "国际经济与贸易": -1,
        "会计学": 4, "工商管理": 0, "信息管理与信息系统": 2,
        "法学": 4, "英语": -2, "新闻传播学": -1, "汉语言文学": -2,
        "动物医学": -2, "食品科学与工程": -3, "教育学": -2,
    }
    
    for m in all_majors:
        base = BASE_OFFSETS.get(m['name'], 0)
        # 检查是否已有真实数据(来自C步骤), 有则保留
        current = m['difficulty_offset']
        if current != 0 and current != base and current not in (-2,-3,-1,0,1,2,3,4,5,6,8,10,12):
            continue  # 已被C步骤更新过, 保留
        
        # 没被C更新过的, 设为基准值
        if current == 0:
            cur.execute("UPDATE majors SET difficulty_offset=? WHERE id=?", (base, m['id']))
    
    conn.commit()
    print(f"  基准偏移已设 {len(BASE_OFFSETS)}个专业")
    
    # Stats
    total_uni = conn.execute("SELECT COUNT(*) FROM universities").fetchone()[0]
    total_adm = conn.execute("SELECT COUNT(*) FROM admission_scores").fetchone()[0]
    total_maj = conn.execute("SELECT COUNT(*) FROM majors").fetchone()[0]
    total_links = conn.execute("SELECT COUNT(*) FROM uni_majors").fetchone()[0]
    
    conn.close()
    print(f"\n=== FINAL ===")
    print(f"  Universities: {total_uni}")
    print(f"  Admission records: {total_adm}")
    print(f"  Majors: {total_maj}")
    print(f"  Major links: {total_links}")
    print(f"  Real scores (A): {len(REAL_2024_HENAN_SCI)} schools")
    print(f"  Real major scores (C): {len(REAL_MAJOR_SCORES)} schools")

if __name__ == "__main__":
    apply_all()
