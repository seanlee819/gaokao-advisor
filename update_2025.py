# 补充缺失的专科线 (大部分省与2024年相同)
DEFAULT_ZHUANKE = {
    "山西":180,"内蒙古":180,"吉林":180,"黑龙江":160,"江西":180,"广西":180,
    "贵州":180,"云南":200,"西藏":190,"甘肃":160,"青海":180,
    "天津":180,"上海":120,"海南":255,
}

def update_2025():
    conn = get_db()
    cur = conn.cursor()
    
    # 先删除2025年旧数据
    cur.execute("DELETE FROM province_lines WHERE year=2025")
    
    # 也删除2025年的录取线 (需要重新生成)
    cur.execute("DELETE FROM admission_scores WHERE year=2025")
    
    count = 0
    for prov, cats in REAL_2025.items():
        for cat, batches in cats.items():
            for batch_name, score in batches:
                cur.execute(
                    "INSERT INTO province_lines (province,year,category,batch,score,rank) VALUES (?,2025,?,?,?,NULL)",
                    (prov, cat, batch_name, score))
                count += 1
            # 补专科线
            if not any("专科" in b[0] or "二段" in b[0] for b in batches):
                if prov in DEFAULT_ZHUANKE:
                    v = DEFAULT_ZHUANKE[prov]
                    bn = "专科批" if prov != "山东" else "二段线"
                    cur.execute(
                        "INSERT INTO province_lines (province,year,category,batch,score,rank) VALUES (?,2025,?,?,?,NULL)",
                        (prov, cat, bn, v))
                    count += 1
    
    conn.commit()
    
    # Stats
    total = cur.execute("SELECT COUNT(*) FROM province_lines WHERE year=2025").fetchone()[0]
    prov_count = cur.execute("SELECT COUNT(DISTINCT province) FROM province_lines WHERE year=2025").fetchone()[0]
    conn.close()
    
    print(f"2025年数据已更新: {total} 条, {prov_count} 省")
    
    # Show sample
    conn = get_db()
    samples = conn.execute("SELECT province,category,batch,score FROM province_lines WHERE year=2025 ORDER BY province,category,score DESC LIMIT 20").fetchall()
    for r in samples:
        print(f"  {r['province']} {r['category']} {r['batch']}: {r['score']}")
    conn.close()

if __name__ == "__main__":
    update_2025()
